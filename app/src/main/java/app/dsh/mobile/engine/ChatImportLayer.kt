package app.dsh.mobile.engine

/**
 * 官方 DeepSeek chat 导出包的导入能力（App 侧装配）。
 *
 * ## 能力从哪来
 * 引擎运行时自带 `@deepseek-ai/dsh-deepseek-chat-import` 包（0.2.2-rc.3 起），它提供
 * 「新建会话」旁的上传按钮、`POST /api/deepseek-chat-import/archive` 路由和
 * `limits` 远程方法。该包自己的 `cordis.patch.yml` 注释写明「Shipped profiles do not
 * include this layer」—— 官方默认不挂，必须由宿主显式加一层 patch 才会激活。
 *
 * ## 为什么走 `--patch` 层而不是 profile bundle
 * 两条路线都实测过（本机 rc.3 真引擎）：
 *  · bundle 路线要求把包名写进 `profiles/web/package.json` 的 `dsh.profile.bundles`，
 *    并且插件页会把它当「用户安装」的插件管理 —— 但包本体在引擎目录里、不在 profile，
 *    pnpm 记账与插件页的升级/卸载语义都对不上；
 *  · patch 路线由 `packageDirFromAnchor` 从**安装目录的 node_modules** 解析包名
 *    （`@deepseek-ai/dsh/package.json` 的 dependencies 里确实声明了它），
 *    因此不需要符号链接、不需要装 npm 包，包随运行时升级即可。
 *    `insert` 解析失败时引擎只打一行 warning 并跳过这一层 —— 老运行时会优雅降级。
 *
 * ## YAML 的唯一硬约束
 * 包名**必须带引号**。裸写 `name: @deepseek-ai/dsh-deepseek-chat-import` 会被 YAML
 * 当成映射缩进错误：`YAMLException: bad indentation of a mapping entry` —— 引擎直接起不来
 * （实测，不是推测）。所以这里由代码拼固定文本，`ChatImportLayerTest` 守着引号。
 *
 * ## 为什么单独一个 object
 * 这段文本既要写进引擎目录，又必须能被 JVM 单测校验（无 Android 依赖）。
 */
object ChatImportLayer {

    /** 官方导入插件的包名（App 只认这一个名字）。 */
    const val PLUGIN_PACKAGE = "@deepseek-ai/dsh-deepseek-chat-import"

    /** patch 层文件名，落在引擎根目录（容器模式靠 `/eng` 挂载同样可达）。 */
    const val LAYER_FILE_NAME = "chat-import-layer.yml"

    /** 插件在引擎目录里的相对位置（判断运行时是否带了这个包）。 */
    const val PLUGIN_ENTRY = "lib/node_modules/$PLUGIN_PACKAGE/lib/index.js"

    /** insert 行的 id：与插件自带 patch 层的 id 一致，重复应用也只是同一条。 */
    const val LAYER_ID = "deepseek-chat-import"

    /**
     * 上传包体积上限：256 MiB（上游默认 512 MiB）。
     *
     * 上游把整包 readBounded 读进内存再解压、不落盘；默认 512 MiB 会同时占住外部 Buffer
     * 与解压后的条目，手机上很容易 OOM。这里按手机收一半。
     */
    const val MAX_UPLOAD_BYTES = 256L * 1024 * 1024

    /** 单个解压条目上限：64 MiB（上游默认 256 MiB），挡住「小包塞大条目」的膨胀型 zip。 */
    const val MAX_ENTRY_BYTES = 64L * 1024 * 1024

    /**
     * 这一层是否应当交给引擎。
     *
     * 两个条件缺一不可：用户打开了开关，且运行时里确实有那个包。少了后者就是
     * 必然失败的 import（引擎会打 warning 但功能不存在），不如不给。
     */
    fun shouldProvide(enabled: Boolean, pluginPresent: Boolean): Boolean = enabled && pluginPresent

    /**
     * patch 层全文（英文注释，不含 CJK —— i18n 门禁扫 Kotlin 字面量）。
     *
     * 换行用 \n 显式拼，不用 trimMargin：缩进是 YAML 语义的一部分，多一层字符串
     * 处理就多一次出错机会（写入侧只做全等比较，文本必须逐字节稳定）。
     */
    fun body(): String = buildString {
        append("# Chat export import layer, generated by the app on every start.\n")
        append("# Do not edit: the file is rewritten when the switch changes or the engine starts.\n")
        append("- insert:\n")
        append("    - id: ").append(LAYER_ID).append("\n")
        append("      name: \"").append(PLUGIN_PACKAGE).append("\"\n")
        // 体积上限必须挂在 insert 条目的 config 上：条目里的 config 会被合并进插件配置，
        // 实测 1000 字节上限时同样的包被拒为 too-large，不写 config 则按上游默认放行。
        append("      config:\n")
        append("        maxUploadBytes: ").append(MAX_UPLOAD_BYTES).append("\n")
        append("        maxEntryBytes: ").append(MAX_ENTRY_BYTES).append("\n")
    }
}
