#!/usr/bin/env node
// Generated colors use @material/material-color-utilities 0.3.0 (Apache-2.0).
// Usage: node scripts/generate-md3-palettes.mjs /path/to/package/index.js
// The package directory may also be supplied instead of its index.js.
// Seeds: Blue #3268AE, Teal #006B5A, Violet #7750A2, Amber #8E5900.
// SchemeTonalSpot uses contrast level 0; the six pairs below must reach 4.5:1.
import { readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const input = process.argv[2];
if (!input || process.argv.length !== 3) {
  throw new Error('Usage: node scripts/generate-md3-palettes.mjs /path/to/package[/index.js]');
}
let entry = path.resolve(input);
if ((await stat(entry)).isDirectory()) entry = path.join(entry, 'index.js');
const manifest = JSON.parse(await readFile(path.join(path.dirname(entry), 'package.json'), 'utf8'));
if (manifest.name !== '@material/material-color-utilities' || manifest.version !== '0.3.0') {
  throw new Error('Expected @material/material-color-utilities version 0.3.0');
}
const { SchemeTonalSpot, Hct, argbFromHex, hexFromArgb } = await import(pathToFileURL(entry).href);
const seeds = [['Blue', '#3268AE'], ['Teal', '#006B5A'], ['Violet', '#7750A2'], ['Amber', '#8E5900']];
const roles = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'surface', 'surfaceDim', 'surfaceBright', 'surfaceContainerLowest',
  'surfaceContainerLow', 'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
  'onSurface', 'surfaceVariant', 'onSurfaceVariant', 'outline', 'outlineVariant',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
];
const pairs = [
  ['onPrimary', 'primary'], ['onPrimaryContainer', 'primaryContainer'],
  ['onSecondary', 'secondary'], ['onTertiary', 'tertiary'],
  ['onSurface', 'surface'], ['onError', 'error'],
];
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const generated = [];
function luminance(argb) {
  const channel = shift => {
    const v = ((argb >>> shift) & 255) / 255;
    return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * channel(16) + 0.7152 * channel(8) + 0.0722 * channel(0);
}
function contrast(a, b) {
  const x = luminance(a), y = luminance(b);
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}
for (const isDark of [false, true]) {
  const mode = isDark ? 'night' : 'day';
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by scripts/generate-md3-palettes.mjs; do not edit.',
    '     @material/material-color-utilities 0.3.0, Apache-2.0; SchemeTonalSpot, contrast 0.',
    '     Seeds: Blue #3268AE, Teal #006B5A, Violet #7750A2, Amber #8E5900. -->',
    '<resources>',
  ];
  for (const [name, seed] of seeds) {
    const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), isDark, 0);
    const ratios = pairs.map(([foreground, background]) => {
      const ratio = contrast(scheme[foreground], scheme[background]);
      if (!Number.isFinite(ratio) || ratio < 4.5) {
        throw new Error(`${mode} ${name}: ${foreground}/${background} contrast ${ratio} < 4.5`);
      }
      return `${foreground}/${background}=${ratio.toFixed(2)}`;
    });
    console.log(`${mode} ${name}: ${ratios.join(' ')}`);
    lines.push(`    <style name="ThemeOverlay.Dsh.Palette.${name}" parent="ThemeOverlay.Material3">`);
    for (const role of roles) {
      const color = hexFromArgb(scheme[role]).toUpperCase();
      if (!/^#[0-9A-F]{6}$/.test(color)) throw new Error(`Invalid color for ${role}: ${color}`);
      const attr = `color${role[0].toUpperCase()}${role.slice(1)}`;
      lines.push(`        <item name="${attr}">${color}</item>`);
    }
    lines.push(`        <item name="android:colorBackground">${hexFromArgb(scheme.background).toUpperCase()}</item>`);
    lines.push(`        <item name="android:windowBackground">${hexFromArgb(scheme.background).toUpperCase()}</item>`);
    lines.push('    </style>');
  }
  lines.push('</resources>', '');
  generated.push([path.join(root, 'app/src/main/res', isDark ? 'values-night' : 'values', 'md3_palettes.xml'), lines.join('\n')]);
}
for (const [file, contents] of generated) await writeFile(file, contents, 'utf8');
